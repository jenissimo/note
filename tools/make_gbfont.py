"""make_gbfont.py - the 4x8 font note/gb packs two characters per tile with.

    python tools/make_gbfont.py src/platform/gb/gb_font.h

The glyphs are 3x5 inside a 4x8 cell: three pixels of ink, one of spacing, one
blank row above and two below.  Three pixels is the narrowest a Latin alphabet
stays distinguishable at -- at two, E, F and B are the same shape.

The source form is the picture, not the hex, because a font is the one kind of
table where a human can see a mistake instantly and cannot see it at all once
it has been turned into bytes.  ASCII 32..95 only: lowercase is folded to
uppercase by the caller, which costs nothing and saves half the table on a
machine where the table lives in ROM beside an interpreter.

Output is one byte per pixel row, ink in the high nibble, so that composing a
tile from a left and a right character is:

    tile[i] = (left[i] & 0xF0) | (right[i] >> 4)
"""

